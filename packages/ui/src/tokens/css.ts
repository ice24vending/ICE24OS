import {
  breakpoints,
  elevation,
  fontFamilies,
  motion,
  radii,
  rem,
  sizes,
  spacing,
  typeScale,
  zIndex,
} from "./foundations.js";
import { primitiveColors } from "./primitives.js";
import { semanticColorRefs } from "./semantic.js";

export type CssVariable = readonly [name: `--${string}`, value: string];

const primitiveVar = (name: string) => `--color-${name}` as const;

/** Every custom property of the light theme, in the order `tokens.css` declares them. */
export const themeCssVariables = (): readonly CssVariable[] => [
  ...Object.entries(primitiveColors).map(([name, value]): CssVariable => [
    primitiveVar(name),
    value,
  ]),
  ...Object.entries(semanticColorRefs).flatMap(([group, refs]) =>
    Object.entries(refs).map(([key, ref]): CssVariable => [
      `--color-${group}-${key}`,
      `var(${primitiveVar(ref)})`,
    ]),
  ),
  ...Object.entries(fontFamilies).map(([name, value]): CssVariable => [
    `--font-family-${name}`,
    value,
  ]),
  ...Object.entries(typeScale).flatMap(([name, style]): CssVariable[] => [
    [`--font-${name}-size`, rem(style.sizePx)],
    [`--font-${name}-line-height`, rem(style.lineHeightPx)],
    [`--font-${name}-weight`, String(style.weight)],
    [
      `--font-${name}`,
      `var(--font-${name}-weight) var(--font-${name}-size) / var(--font-${name}-line-height) var(--font-family-${style.family})`,
    ],
  ]),
  ...Object.entries(spacing).map(([step, px]): CssVariable => [`--space-${step}`, rem(px)]),
  ...Object.entries(radii).map(([name, px]): CssVariable => [
    `--radius-${name}`,
    name === "pill" ? `${px}px` : rem(px),
  ]),
  ...Object.entries(sizes).map(([name, px]): CssVariable => [`--size-${name}`, rem(px)]),
  ...Object.entries(elevation).map(([name, value]): CssVariable => [`--shadow-${name}`, value]),
  ...Object.entries(motion.duration).map(([name, ms]): CssVariable => [
    `--motion-duration-${name}`,
    `${ms}ms`,
  ]),
  ...Object.entries(motion.easing).map(([name, value]): CssVariable => [
    `--motion-easing-${name}`,
    value,
  ]),
  ...Object.entries(zIndex).map(([name, value]): CssVariable => [`--z-${name}`, String(value)]),
  ...Object.entries(breakpoints).map(([name, px]): CssVariable => [
    `--breakpoint-${name}`,
    rem(px),
  ]),
];

const block = (selector: string, variables: readonly CssVariable[], indent = "") =>
  [
    `${indent}${selector} {`,
    ...variables.map(([name, value]) => `${indent}  ${name}: ${value};`),
    `${indent}}`,
  ].join("\n");

/**
 * Source of `tokens.css`. The file is generated (`pnpm tokens:generate`) and a unit test fails
 * when it drifts from these objects.
 */
export const renderTokensCss = (): string =>
  [
    "/*",
    " * ICE24 Design System tokens — GENERATED by `pnpm tokens:generate` from packages/ui/src/tokens.",
    " * Do not edit by hand. Brand palette approved 15/10/2026 (ADR-025); typography provisional.",
    " */",
    "",
    block(":root", themeCssVariables()),
    "",
    "@media (prefers-reduced-motion: reduce) {",
    block(
      ":root",
      Object.keys(motion.duration).map((name): CssVariable => [`--motion-duration-${name}`, "0ms"]),
      "  ",
    ),
    "}",
    "",
  ].join("\n");
